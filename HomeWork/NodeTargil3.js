const numbers=[0,5,0,12,-3,0,7,0,9]// הגדרת מערך של מספרים שלמים
let zeroCount=0;// הגדרת משנה לספירת האפסים ואתחולו לאפס
for(let i=0;i<numbers.length;i++)// לולאה שעוברת על כל איברי המערך מההתחלה ועד הסוף
{
    numbers[i]==0?zeroCount++ :null; // בדיקה בעזרת ביטוי מותנה (Ternary) האם המספר הנוכחי שווה לאפס, ואם כן הוספת 1 למונה
}
console.log("zeroCounts:"+zeroCount);// הדפסת כמות האפסים הכוללת למסך